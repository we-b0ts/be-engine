#[test]
fn bounded_redis_random_values_validate_both_sides_without_equal_length_for_strings() {
    let compare = |a: Value, b: Value, format, length, max| {
        compare_bounded_random(&a, &b, &format, length, max)
    };
    assert!(
        compare(
            json!("6fa459ea-ee8a-3ca4-894e-db77e160355e"),
            json!("01234567-89ab-4def-8123-456789abcdef"),
            RandomEncoding::Uuid,
            Some(36),
            None
        )
        .is_ok()
    );
    assert!(
        compare(
            json!("gen1@source"),
            json!("gen123456@longer-target"),
            RandomEncoding::String,
            None,
            Some(255)
        )
        .is_ok()
    );
    for invalid in [
        json!(""),
        json!("x".repeat(256)),
        json!("line\nbreak"),
        json!(null),
        json!(123),
    ] {
        for (a, b) in [
            (invalid.clone(), json!("gen1@source")),
            (json!("gen1@source"), invalid),
        ] {
            assert!(compare(a, b, RandomEncoding::String, None, Some(255)).is_err());
        }
    }
    for invalid in [
        "0123456789ab4def8123456789abcdef",
        "01234567-89AB-4DEF-8123-456789ABCDEF",
        "not-a-uuid",
    ] {
        assert!(
            compare(
                json!(invalid),
                json!("01234567-89ab-4def-8123-456789abcdef"),
                RandomEncoding::Uuid,
                Some(36),
                None
            )
            .is_err()
        );
    }
}
use crate::policy::{Proof, TimeAnchor, TimeRelation, TimestampFormat, native::*};

pub(super) fn proof<T>(contract: T) -> Proven<T> {
    Proven {
        contract,
        proof: Proof {
            source: "source/crypto.rs:1".into(),
            fact: "generated by the selected Source contract".into(),
        },
    }
}

fn encrypted(fields: BTreeMap<String, Proven<PlaintextContract>>) -> GeneratedResponse {
    GeneratedResponse::EncryptedJson {
        envelope: CipherEnvelope::Base64IvAesCbcPkcs7,
        key: EncryptionKey::Startup {
            source: StartupKey::TargetEnv {
                name: "CRYPTO_KEY".into(),
            },
        },
        fields,
    }
}

fn encode<C: BlockEncrypt + KeyInit>(plaintext: &[u8], key: &[u8], iv: [u8; 16]) -> String {
    let cipher = C::new_from_slice(key).unwrap();
    let padding = 16 - plaintext.len() % 16;
    let mut padded = plaintext.to_vec();
    padded.resize(padded.len() + padding, padding as u8);
    let mut envelope = iv.to_vec();
    let mut previous = iv;
    for chunk in padded.as_chunks_mut::<16>().0 {
        for (byte, previous) in chunk.iter_mut().zip(previous) {
            *byte ^= previous;
        }
        cipher.encrypt_block(Block::<C>::from_mut_slice(chunk));
        previous.copy_from_slice(chunk);
        envelope.extend_from_slice(chunk);
    }
    STANDARD.encode(envelope)
}

#[test]
fn cbc_decryption_matches_aes128_cbc_known_vector() {
    let bytes = |value: &str| {
        value
            .as_bytes()
            .as_chunks::<2>()
            .0
            .iter()
            .map(|pair| u8::from_str_radix(std::str::from_utf8(pair).unwrap(), 16).unwrap())
            .collect::<Vec<_>>()
    };
    let key = bytes("2b7e151628aed2a6abf7158809cf4f3c");
    let mut envelope = bytes("000102030405060708090a0b0c0d0e0f");
    let mut block = bytes("7649abac8119b246cee98e9b12e9197d");
    envelope.extend_from_slice(&block);
    decrypt_blocks::<Aes128>(&mut block, &envelope, &key).unwrap();
    assert_eq!(block, bytes("6bc1bee22e409f96e93d7e117393172a"));
}

#[test]
fn different_ivs_preserve_full_plaintext_business_comparison_for_all_aes_key_sizes() {
    for size in [16, 24, 32] {
        let key = vec![3; size];
        let make = |value: &[u8], iv| match size {
            16 => encode::<Aes128>(value, &key, iv),
            24 => encode::<Aes192>(value, &key, iv),
            _ => encode::<Aes256>(value, &key, iv),
        };
        let source = Value::String(make(
            br#"{"name":"task","roles":["read","write"]}"#,
            [1; 16],
        ));
        let same = Value::String(make(
            br#"{"roles":["read","write"],"name":"task"}"#,
            [2; 16],
        ));
        let changed = Value::String(make(br#"{"roles":["admin"],"name":"task"}"#, [2; 16]));
        assert!(
            compare_value(
                &source,
                &same,
                &encrypted(BTreeMap::new()),
                Some(&key),
                "cipher",
                AnchorClocks::default()
            )
            .unwrap()
            .passed()
        );
        assert_eq!(
            compare_value(
                &source,
                &changed,
                &encrypted(BTreeMap::new()),
                Some(&key),
                "cipher",
                AnchorClocks::default()
            )
            .unwrap_err(),
            GeneratedError::ContractMismatch
        );
    }
}

#[test]
fn encrypted_plaintext_composes_unordered_time_and_uuid_with_strict_remainder() {
    let key = [9; 32];
    let fields = BTreeMap::from([
        ("/roles".into(), proof(PlaintextContract::Unordered)),
        (
            "/expires".into(),
            proof(PlaintextContract::Time(NativeTime {
                format: TimestampFormat::UnixSeconds,
                relation: TimeRelation::PreserveOffset,
                anchor: TimeAnchor::DependencyRequestStart,
                utc_offset: None,
                clock_group: None,
            })),
        ),
        ("/jti".into(), proof(PlaintextContract::UuidV4)),
    ]);
    let contract = encrypted(fields);
    let source = json!({"user":7,"roles":["read","write"],"expires":1_700_000_060,"jti":"f5a90118-572c-48a5-8103-d870bdc7b8e5"});
    let target = json!({"user":7,"roles":["write","read"],"expires":1_800_000_060,"jti":"332348d4-46d5-467b-a179-d8aee5e04b5f"});
    let clocks = AnchorClocks {
        dependency: super::super::time::ClockPair {
            source: Some(chrono::Utc.timestamp_opt(1_700_000_000, 0).unwrap()),
            target: Some(chrono::Utc.timestamp_opt(1_800_000_000, 0).unwrap()),
        },
        ..Default::default()
    };
    let source = json!(encode::<Aes256>(
        &serde_json::to_vec(&source).unwrap(),
        &key,
        [1; 16]
    ));
    let target = json!(encode::<Aes256>(
        &serde_json::to_vec(&target).unwrap(),
        &key,
        [2; 16]
    ));
    let compared =
        compare_value(&source, &target, &contract, Some(&key), "cipher", clocks).unwrap();
    assert!(compared.passed());
    assert_eq!(compared.time_validations["cipher"], 1);
    assert_eq!(
        compare_value(
            &source,
            &target,
            &contract,
            Some(&key),
            "cipher",
            AnchorClocks::default()
        )
        .unwrap_err(),
        GeneratedError::ContractMismatch
    );
}

#[test]
fn cbc_rejects_invalid_layout_padding_json_precision_and_keys() {
    let key = [4; 16];
    let source = json!(encode::<Aes128>(b"{}", &key, [0; 16]));
    let contract = encrypted(BTreeMap::new());
    assert_eq!(
        compare_value(
            &source,
            &source,
            &contract,
            None,
            "cipher",
            AnchorClocks::default()
        )
        .unwrap_err(),
        GeneratedError::MissingKey
    );
    assert_eq!(
        compare_value(
            &source,
            &source,
            &contract,
            Some(&key[..15]),
            "cipher",
            AnchorClocks::default()
        )
        .unwrap_err(),
        GeneratedError::InvalidKeyLength
    );
    let mut envelope = STANDARD.decode(source.as_str().unwrap()).unwrap();
    envelope[15] ^= 1;
    assert_eq!(
        decrypt(&STANDARD.encode(envelope), &key).unwrap_err(),
        GeneratedError::InvalidCiphertext
    );
    assert_eq!(
        decrypt(&STANDARD.encode([0; 16]), &key).unwrap_err(),
        GeneratedError::InvalidCiphertext
    );
    for invalid in [
        br#"{"x":1,"x":2}"#.as_slice(),
        br#"{"x":9007199254740993.0}"#.as_slice(),
        &[255],
    ] {
        let invalid = json!(encode::<Aes128>(invalid, &key, [3; 16]));
        assert_eq!(
            compare_value(
                &source,
                &invalid,
                &contract,
                Some(&key),
                "cipher",
                AnchorClocks::default()
            )
            .unwrap_err(),
            GeneratedError::InvalidJson
        );
    }
}

