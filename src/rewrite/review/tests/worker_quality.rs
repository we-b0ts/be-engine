//! Ordinary worker and integration reviews never execute the final Cargo gates.
use super::*;
use crate::rewrite::quality::QualityScope;
use crate::rewrite::worker::model::RewriteWorkerActivity;
use crate::rewrite::worker::runtime::RewriteWorkerReportOptions;

fn rust_project(root: &Path, source: &str) {
    fs::write(
        root.join("Cargo.toml"),
        "[package]\nname = \"worker-source-review-fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[lib]\npath = \"lib.rs\"\n",
    )
    .unwrap();
    fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"worker-source-review-fixture\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    fs::write(root.join(".gitignore"), "/.traffic-e2e/local/\n/target/\n").unwrap();
    fs::write(root.join("lib.rs"), source).unwrap();
    git(
        root,
        &["add", "Cargo.toml", "Cargo.lock", ".gitignore", "lib.rs"],
    );
    git(
        root,
        &[
            "commit",
            "-qm",
            "API implementation awaiting integration quality",
        ],
    );
}

fn handoff(root: &Path, report: &RewriteReviewReport) -> RewriteWorkerReportOptions {
    RewriteWorkerReportOptions {
        target_root: root.into(),
        agent_handle: "review-worker".into(),
        activity: RewriteWorkerActivity::HandoffReady,
        handoff_id: Some(report.head_revision.clone()),
        review_report: Some(report.report_path.clone()),
    }
}

#[test]
fn ordinary_worker_and_integration_review_do_not_run_repository_commands() {
    // These valid-syntax crates deliberately contain formatting, test or lint
    // problems. Ordinary delivery review must leave Cargo checks to the final
    // pre-revalidation stage.
    for (source, failed_gate) in [
        ("pub fn value( )->u8{1}\n", "rust-format"),
        (
            "pub fn value() -> u8 {\n    1\n}\n\n#[test]\nfn changed_behavior() {\n    assert_eq!(value(), 2);\n}\n",
            "rust-test",
        ),
        ("pub fn value() -> u8 {\n    return 1;\n}\n", "rust-clippy"),
    ] {
        let (target, scope) = setup();
        rust_project(target.path(), source);
        let quality_logs = crate::internal_runtime::root(target.path()).join("rewrite/quality");
        assert!(!target.path().join("target").exists());
        assert!(!quality_logs.exists());

        let worker = check(options(target.path(), scope.clone())).unwrap();
        assert_eq!(worker.status, ReviewStatus::Passed, "{failed_gate}");
        assert_eq!(worker.required_gates, ["source-review", "replay-isolation"]);
        let quality = worker.quality.as_ref().unwrap();
        assert_eq!(quality.scope, Some(QualityScope::Worker));
        assert!(quality.commands.is_empty());
        assert!(!target.path().join("target").exists());
        assert!(!quality_logs.exists());
        let mut delivery = handoff(target.path(), &worker);
        worker::runtime::report(delivery.clone()).unwrap();

        let integrated = check(RewriteReviewOptions {
            integration: true,
            handoff_id: delivery.handoff_id.clone(),
            ..options(target.path(), scope.clone())
        })
        .unwrap();
        assert_eq!(integrated.head_revision, worker.head_revision);
        assert_eq!(integrated.status, ReviewStatus::Passed, "{failed_gate}");
        assert_eq!(
            integrated.required_gates,
            ["source-review", "replay-isolation"]
        );
        let quality = integrated.quality.as_ref().unwrap();
        assert_eq!(quality.scope, Some(QualityScope::Integration));
        assert!(quality.commands.is_empty());
        assert!(!target.path().join("target").exists());
        assert!(!quality_logs.exists());
        assert!(
            integrated
                .next_step
                .contains("ordinary review does not run fmt, tests or Clippy")
        );
        delivery.activity = RewriteWorkerActivity::Integrated;
        delivery.review_report = Some(integrated.report_path);
        worker::runtime::report(delivery).unwrap();
        let state = RewriteStore::new(target.path())
            .unwrap()
            .load()
            .unwrap()
            .unwrap();
        assert_eq!(
            worker::runtime::observation(&state, &scope)
                .unwrap()
                .activity,
            RewriteWorkerActivity::Integrated
        );
        assert!(!state.api_inventory.iter().all(|item| item.status.is_done()));
    }
}

#[test]
fn worker_source_only_review_still_rejects_replay_and_private_artifact_keywords() {
    let (target, scope) = setup();
    rust_project(target.path(), "pub fn value() -> u8 {\n    1\n}\n");
    // Production-only markers must be exercised in a production Rust path.
    fs::create_dir_all(target.path().join("src")).unwrap();
    for (marker, rule) in [
        ("cache.trp.test", "replay_hostname"),
        ("TRAFFIC_E2E_REPLAY_URL", "traffic_e2e_environment"),
        ("198.18.0.1", "fake_ip_range"),
        (".traffic-e2e/local/private.json", "local_runtime_path"),
        ("dependencies.jsonl", "recording_artifact"),
    ] {
        fs::write(
            target.path().join("src/client.rs"),
            format!("pub const ADDRESS: &str = {marker:?};\n"),
        )
        .unwrap();
        let report = check(options(target.path(), scope.clone())).unwrap();
        assert_eq!(report.status, ReviewStatus::ChangesRequired, "{marker}");
        assert_eq!(report.required_gates, ["source-review", "replay-isolation"]);
        let quality = report.quality.as_ref().unwrap();
        assert_eq!(quality.scope, Some(QualityScope::Worker));
        assert!(quality.commands.is_empty());
        let isolation = serde_json::to_value(&quality.replay_isolation).unwrap();
        assert!(
            isolation["violations"]
                .as_array()
                .unwrap()
                .iter()
                .any(|violation| {
                    violation["rule"] == rule && violation["file"] == "src/client.rs"
                }),
            "{isolation}"
        );
        assert!(worker::runtime::report(handoff(target.path(), &report)).is_err());
        assert!(!target.path().join("target").exists());
    }
}
