#[test]
fn coordinator_status_and_admission_never_execute_quality_commands() {
    let directory = tempfile::tempdir().unwrap();
    let counter = directory.path().join("quality-invocations");
    let target = target();
    enable_standard_rust_checks(
        target.path(),
        &format!(
            "use std::fs;\n\nfn main() {{\n    println!(\"cargo:rerun-if-changed=build.rs\");\n    let path = {path:?};\n    let mut count = fs::read_to_string(path).unwrap_or_default();\n    count.push('x');\n    fs::write(path, count).unwrap();\n}}\n",
            path = counter.to_string_lossy(),
        ),
    );
    let store = RewriteStore::new(target.path()).unwrap();
    let state = store.load().unwrap().unwrap();
    assert!(gate(target.path(), &state, "master").unwrap().is_some());
    assert!(!counter.exists());
    let candidate = worktree(target.path(), directory.path(), "candidate");
    commit_code(&candidate);
    let reviewed = check(options(target.path(), &candidate, None)).unwrap();
    assert_eq!(reviewed.status, ReviewStatus::Passed);
    let review_invocations = fs::read_to_string(&counter).unwrap();
    assert!(!review_invocations.is_empty());
    assert!(gate(target.path(), &state, "master").unwrap().is_some());
    git(
        target.path(),
        &["merge", "--ff-only", &reviewed.head_revision],
    );
    accept(target.path().into(), reviewed.report_path).unwrap();
    assert!(gate(target.path(), &state, "master").unwrap().is_none());
    crate::rewrite::status_rewrite(crate::rewrite::RewriteContext {
        target_root: target.path().into(),
    })
    .unwrap();
    assert_eq!(fs::read_to_string(&counter).unwrap(), review_invocations);

    // Engine progress publication changes Git history without changing the
    // reviewed code or canonical execution inputs. Reuse the accepted receipt.
    let progress = crate::verification_progress::ProgressReport::new(
        crate::verification_progress::VerificationStage::Progress,
    );
    crate::verification_progress::write(
        &target.path().join(".traffic-e2e/progress.yaml"),
        &progress,
    )
    .unwrap();
    git(target.path(), &["add", ".traffic-e2e/progress.yaml"]);
    git(target.path(), &["commit", "-qm", "publish engine progress"]);
    assert_ne!(
        candidate::head(target.path()).unwrap(),
        reviewed.head_revision
    );
    assert!(terminal_current(target.path(), &state));
    assert!(gate(target.path(), &state, "master").unwrap().is_none());
    crate::rewrite::status_rewrite(crate::rewrite::RewriteContext {
        target_root: target.path().into(),
    })
    .unwrap();
    assert_eq!(fs::read_to_string(&counter).unwrap(), review_invocations);

    // Source-proof metadata changes require review even without a code change.
    git(
        target.path(),
        &[
            "commit",
            "--allow-empty",
            "-qm",
            "update source evidence\n\nHardcode-Source-Evidence: lib.rs:1:1 <= source@revision:lib.rs:1:1",
        ],
    );
    assert!(!terminal_current(target.path(), &state));
    assert!(gate(target.path(), &state, "master").unwrap().is_some());
    assert_eq!(fs::read_to_string(&counter).unwrap(), review_invocations);

    fs::write(target.path().join("lib.rs"), "pub fn value() -> u8 { 3 }\n").unwrap();
    assert!(gate(target.path(), &state, "master").unwrap().is_some());
    crate::rewrite::status_rewrite(crate::rewrite::RewriteContext {
        target_root: target.path().into(),
    })
    .unwrap();
    assert_eq!(fs::read_to_string(&counter).unwrap(), review_invocations);

    // Losing the receipt cannot downgrade revalidation to initial diagnosis.
    // Persisted history requires a replacement review but never proves a pass.
    fs::remove_file(integrated_path(target.path())).unwrap();
    let mut revalidation = store.load().unwrap().unwrap();
    assert!(revalidation.delivery_review_required);
    revalidation.phase = crate::rewrite::RewritePhase::ApiPending;
    store.save(&revalidation).unwrap();
    assert!(!terminal_current(target.path(), &revalidation));
    assert!(matches!(
        required_action(target.path(), &revalidation).unwrap(),
        Some(RewriteAction::SourceReviewRequired { .. })
    ));
    let status = crate::rewrite::status_rewrite(crate::rewrite::RewriteContext {
        target_root: target.path().into(),
    })
    .unwrap();
    assert!(matches!(
        status.action,
        RewriteAction::SourceReviewRequired { .. }
    ));
    assert_eq!(fs::read_to_string(&counter).unwrap(), review_invocations);

    // A malformed receipt has the same actionable recovery as an absent one.
    fs::write(integrated_path(target.path()), "{broken report").unwrap();
    let status = crate::rewrite::status_rewrite(crate::rewrite::RewriteContext {
        target_root: target.path().into(),
    })
    .unwrap();
    assert!(matches!(
        status.action,
        RewriteAction::SourceReviewRequired { .. }
    ));
    assert_eq!(fs::read_to_string(&counter).unwrap(), review_invocations);
}

#[test]
fn external_change_can_refresh_review_at_the_canonical_commit_without_another_merge() {
    let directory = tempfile::tempdir().unwrap();
    let target = target();
    let integration = worktree(target.path(), directory.path(), "integration");
    let report = check(options(target.path(), &integration, None)).unwrap();
    assert!(report.quality.as_ref().unwrap().commands.is_empty());
    accept(target.path().into(), report.report_path).unwrap();

    // External changes invalidate the receipt and leave the retained worktree behind.
    commit_code(target.path());
    let published = candidate::head(target.path()).unwrap();
    let store = RewriteStore::new(target.path()).unwrap();
    let mut state = store.load().unwrap().unwrap();
    state.phase = crate::rewrite::RewritePhase::ApiPending;
    store.save(&state).unwrap();
    assert!(matches!(
        required_action(target.path(), &state).unwrap(),
        Some(RewriteAction::SourceReviewRequired { .. })
    ));
    assert!(check(options(target.path(), &integration, None)).is_err());

    git(&integration, &["merge", "--ff-only", &published]);
    let report = check(options(target.path(), &integration, None)).unwrap();
    assert_eq!(report.status, ReviewStatus::Passed);
    assert_eq!(report.head_revision, published);
    assert_eq!(report.base_revision, published);
    assert!(report.scope.is_none());
    accept(target.path().into(), report.report_path).unwrap();
    let state = store.load().unwrap().unwrap();
    assert!(terminal_current(target.path(), &state));
    assert!(required_action(target.path(), &state).unwrap().is_none());
    assert!(state.worker_bindings.is_empty());
    assert_eq!(candidate::head(target.path()).unwrap(), published);
}

#[test]
fn unpublished_candidates_require_publication_instead_of_repeated_checks() {
    for variant in ["code_change", "empty_merge"] {
        let directory = tempfile::tempdir().unwrap();
        let counter = directory.path().join("checks");
        let target = target();
        enable_standard_rust_checks(
            target.path(),
            &format!(
                "use std::fs;\n\nfn main() {{\n    println!(\"cargo:rerun-if-changed=build.rs\");\n    let path = {path:?};\n    let mut count = fs::read_to_string(path).unwrap_or_default();\n    count.push('x');\n    fs::write(path, count).unwrap();\n}}\n",
                path = counter.to_string_lossy(),
            ),
        );
        let integration = worktree(target.path(), directory.path(), "integration");
        if variant == "empty_merge" {
            git(
                &integration,
                &["commit", "--allow-empty", "-qm", "old integration metadata"],
            );
            commit_code(target.path());
            let published = candidate::head(target.path()).unwrap();
            git(
                &integration,
                &["merge", "-qm", "refresh old branch", &published],
            );
            assert!(
                source_diff::git_text(&integration, &["diff", &published, "HEAD", "--"])
                    .unwrap()
                    .is_empty()
            );
        } else {
            commit_code(&integration);
        }
        let published = candidate::head(target.path()).unwrap();
        let report = check(options(target.path(), &integration, None)).unwrap();
        assert_eq!(report.status, ReviewStatus::Passed);
        let review_invocations = fs::read_to_string(&counter).unwrap();
        assert!(!review_invocations.is_empty());
        assert_ne!(report.head_revision, published);
        let store = RewriteStore::new(target.path()).unwrap();
        let before = serde_json::to_value(store.load().unwrap().unwrap()).unwrap();
        let error = accept(target.path().into(), report.report_path.clone())
            .unwrap_err()
            .to_string();
        assert!(
            error.contains("reviewed candidate is not published"),
            "{variant}: {error}"
        );
        assert!(error.contains(&format!("published_head={published}")));
        assert!(error.contains(&format!("reviewed_head={}", report.head_revision)));
        assert!(error.contains(&format!("reviewed_canonical_base={published}")));
        assert_eq!(candidate::head(target.path()).unwrap(), published);
        assert_eq!(
            serde_json::to_value(store.load().unwrap().unwrap()).unwrap(),
            before
        );
        assert!(!integrated_path(target.path()).exists());

        // Publish, then admit the same receipt without executing checks again.
        git(
            target.path(),
            &["merge", "--ff-only", &report.head_revision],
        );
        accept(target.path().into(), report.report_path).unwrap();
        assert!(terminal_current(
            target.path(),
            &store.load().unwrap().unwrap()
        ));
        assert_eq!(fs::read_to_string(&counter).unwrap(), review_invocations);
    }
}

#[test]
fn canonical_commit_drift_requires_reconciliation_even_with_identical_files() {
    let target = target();
    let directory = tempfile::tempdir().unwrap();
    let integration = worktree(target.path(), directory.path(), "integration");
    let report = check(options(target.path(), &integration, None)).unwrap();
    git(
        target.path(),
        &["commit", "--allow-empty", "-qm", "external metadata"],
    );
    let published = candidate::head(target.path()).unwrap();
    let error = accept(target.path().into(), report.report_path)
        .unwrap_err()
        .to_string();
    assert!(
        error.contains("canonical HEAD changed from the reviewed base"),
        "{error}"
    );
    assert!(error.contains(&format!("published_head={published}")));
    assert!(error.contains(&format!("reviewed_head={}", report.head_revision)));
    assert!(!error.contains("reviewed candidate is not published"));
    assert_eq!(candidate::head(target.path()).unwrap(), published);
    assert!(!integrated_path(target.path()).exists());
}
