use std::fs;
use std::path::PathBuf;

use anyhow::{Context, Result, ensure};
use serde::Serialize;

use super::config::{ReplayPolicyDocument, validate_document};
use crate::config::edit::create_atomic;

const VERIFICATION_POLICY_PATH: &str = ".traffic-e2e/verification.yaml";
const VERIFICATION_POLICY_TEMPLATE: &str = r#"# Generated by repository configuration initialization.
version: 3
expected_response: assertions_only
dependency_rules: []
response_settings:
  comparison:
    source_match: before
response_rules:
  json: {}
  protobuf: {}
  hessian2: {}
"#;

#[derive(Debug, Clone)]
pub struct ReplayPolicyInitOptions {
    pub target_root: PathBuf,
}

#[derive(Debug, Clone, Serialize)]
pub struct ReplayPolicyInitResult {
    pub policy: PathBuf,
    pub version: u8,
    pub expected_response: &'static str,
}

pub fn initialize_replay_policy(
    options: ReplayPolicyInitOptions,
) -> Result<ReplayPolicyInitResult> {
    let target_root = fs::canonicalize(&options.target_root).with_context(|| {
        format!(
            "failed to resolve target root {}",
            options.target_root.display()
        )
    })?;
    ensure!(target_root.is_dir(), "target root must be a directory");
    let rendered = render_validated_replay_policy()?;

    let policy_path = target_root.join(VERIFICATION_POLICY_PATH);
    create_atomic(&policy_path, rendered.as_bytes())?;
    Ok(ReplayPolicyInitResult {
        policy: policy_path,
        version: 3,
        expected_response: "assertions_only",
    })
}

pub(crate) fn render_validated_replay_policy() -> Result<String> {
    let document = serde_yaml::from_str::<ReplayPolicyDocument>(VERIFICATION_POLICY_TEMPLATE)
        .context("generated verification policy is not valid YAML")?;
    validate_document(&document).context("generated verification policy failed validation")?;
    Ok(VERIFICATION_POLICY_TEMPLATE.to_string())
}

#[cfg(test)]
mod tests {
    use tempfile::tempdir;

    use super::*;
    use crate::replay::validate_replay_policy;

    #[test]
    fn initializes_empty_verification_policy_once() {
        let target = tempdir().unwrap();
        let result = initialize_replay_policy(ReplayPolicyInitOptions {
            target_root: target.path().to_path_buf(),
        })
        .unwrap();
        let report = validate_replay_policy(&result.policy).unwrap();
        assert!(result.policy.ends_with(".traffic-e2e/verification.yaml"));
        assert_eq!(report.version, 3);
        assert_eq!(
            report.comparison.source_match,
            crate::replay::ComparisonSourceMatch::Before
        );
        assert!(report.dependency_rule_ids.is_empty());
        assert!(report.response_rule_ids.is_empty());

        let error = initialize_replay_policy(ReplayPolicyInitOptions {
            target_root: target.path().to_path_buf(),
        })
        .unwrap_err();
        assert!(error.to_string().contains("already exists"));
    }
}
