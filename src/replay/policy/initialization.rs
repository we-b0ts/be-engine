use std::fs;
use std::path::PathBuf;

use anyhow::{Context, Result, ensure};
use serde::Serialize;

use super::config::{ReplayPolicyDocument, validate_document};
use crate::config::edit::create_atomic;

const REPLAY_POLICY_PATH: &str = ".traffic-e2e/replay.yaml";
const REPLAY_POLICY_TEMPLATE: &str = r#"# Generated by `traffic-e2e config replay init`.
version: 2
expected_response: assertions_only
rules: []
response_rules:
  dynamic: {}
  unordered: {}
"#;

#[derive(Debug, Clone)]
pub struct ReplayPolicyInitOptions {
    pub target_root: PathBuf,
}

#[derive(Debug, Clone, Serialize)]
pub struct ReplayPolicyInitResult {
    pub policy: PathBuf,
    pub version: u8,
    pub expected_response: &'static str,
}

pub fn initialize_replay_policy(
    options: ReplayPolicyInitOptions,
) -> Result<ReplayPolicyInitResult> {
    let target_root = fs::canonicalize(&options.target_root).with_context(|| {
        format!(
            "failed to resolve target root {}",
            options.target_root.display()
        )
    })?;
    ensure!(target_root.is_dir(), "target root must be a directory");
    let document = serde_yaml::from_str::<ReplayPolicyDocument>(REPLAY_POLICY_TEMPLATE)
        .context("generated replay policy is not valid YAML")?;
    validate_document(&document).context("generated replay policy failed validation")?;

    let policy_path = target_root.join(REPLAY_POLICY_PATH);
    create_atomic(&policy_path, REPLAY_POLICY_TEMPLATE.as_bytes())?;
    Ok(ReplayPolicyInitResult {
        policy: policy_path,
        version: 2,
        expected_response: "assertions_only",
    })
}

#[cfg(test)]
mod tests {
    use tempfile::tempdir;

    use super::*;
    use crate::replay::validate_replay_policy;

    #[test]
    fn initializes_empty_assertion_only_policy_once() {
        let target = tempdir().unwrap();
        let result = initialize_replay_policy(ReplayPolicyInitOptions {
            target_root: target.path().to_path_buf(),
        })
        .unwrap();
        let report = validate_replay_policy(&result.policy).unwrap();
        assert_eq!(report.version, 2);
        assert!(report.rule_ids.is_empty());
        assert!(report.response_rule_ids.is_empty());

        let error = initialize_replay_policy(ReplayPolicyInitOptions {
            target_root: target.path().to_path_buf(),
        })
        .unwrap_err();
        assert!(error.to_string().contains("already exists"));
    }
}
